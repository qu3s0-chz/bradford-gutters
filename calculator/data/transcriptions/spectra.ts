const coilNote = "Coil sold by the pound, about 350 lb per coil.";

function coil(
  width: string,
  widthCode: string,
  gauge: "027" | "032",
  format: "full" | "spin",
  text: string,
): TranscribedRow {
  return {
    id: `spectra:coil-${gauge}-${widthCode}-${format}`,
    text,
    price: 3.95,
    unit: "Pound",
    name: `Gutter coil .${gauge} x ${width}, ${format === "full" ? "full coil" : "spin down"}`,
    sku: `${gauge}${widthCode}__`,
    category: "gutter-coil-stock",
    size: width,
    gauge: `.${gauge}`,
    color: "any (code suffix)",
    notes: [coilNote, "SKU built from the printed code pattern; confirm with Spectra."],
  };
}

function bothGauges(
  width: string,
  widthCode: string,
  format: "full" | "spin",
  text: string,
) {
  return [
    coil(width, widthCode, "027", format, text),
    coil(width, widthCode, "032", format, text),
  ];
}

function pair(
  base: Omit<TranscribedRow, "id" | "name" | "sku">,
  variants: { id: string; name: string; sku: string }[],
): TranscribedRow[] {
  return variants.map((variant) => ({ ...base, ...variant }));
}

