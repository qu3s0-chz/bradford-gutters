// Builds the catalog, canonical mapping and review list from the transcriptions.
// Run with: npm.cmd run catalog

import { mkdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { canonicalItems } from "../data/canonical.ts";
import { spectra } from "../data/transcriptions/spectra.ts";
import { townCountry } from "../data/transcriptions/town-country.ts";
import {
  buildCatalog,
  buildMappingTable,
  buildReview,
  toCsv,
  type MappingRow,
  type SupplierPrice,
} from "../lib/build.ts";
import { categories } from "../lib/types.ts";

const transcriptions = [spectra, townCountry];
const suppliers = transcriptions.map((t) => t.supplier);
const catalog = buildCatalog(transcriptions);
const mappingTable = buildMappingTable(canonicalItems, catalog);
const review = buildReview(suppliers, catalog, canonicalItems);

const outDir = join(import.meta.dirname, "..", "output");
mkdirSync(outDir, { recursive: true });

const write = (name: string, content: string) =>
  writeFileSync(join(outDir, name), content, "utf8");

write(
  "catalog.json",
  JSON.stringify({ suppliers, items: catalog }, null, 2) + "\n",
);
write("canonical.json", JSON.stringify(canonicalItems, null, 2) + "\n");

write(
  "catalog.csv",
  toCsv([
    [
      "id", "supplier", "category", "name", "sku", "size", "color", "gauge",
      "unit", "unit_as_printed", "pack_qty", "carton_qty", "unit_price",
      "price_status", "source_file", "page", "section", "price_list_date",
      "as_of", "raw_text", "gutter_relevant", "notes", "needs_review",
    ],
    ...catalog.map((i) => [
      i.id, i.supplier, i.category, i.name, i.sku, i.size, i.color, i.gauge,
      i.unit, i.unitAsPrinted, i.packQty, i.cartonQty, i.unitPrice,
      i.priceStatus, i.sourceFile, i.page, i.section, i.priceListDate,
      i.asOf, i.rawText, i.gutterRelevant, i.notes.join(" "), i.review.join(" "),
    ]),
  ]),
);

const supplierIds = suppliers.map((s) => s.id);
const priceCells = (price: SupplierPrice | undefined) =>
  price
    ? [price.itemId, price.unitPrice, price.unitsPerPurchase, price.perBaseUnit, price.confidence]
    : ["not carried", null, null, null, null];

write(
  "canonical-map.csv",
  toCsv([
    [
      "canonical_id", "name", "category", "base_unit", "status", "cheapest",
      ...supplierIds.flatMap((s) => [
        `${s}_item`, `${s}_price`, `${s}_units_per_purchase`, `${s}_per_base_unit`, `${s}_confidence`,
      ]),
      "alternates",
    ],
    ...mappingTable.map((row) => [
      row.canonicalId, row.name, row.category, row.baseUnit, row.status, row.cheapestSupplier,
      ...supplierIds.flatMap((s) => priceCells(row.suppliers[s]?.best)),
      Object.values(row.suppliers)
        .flatMap(({ others }) => others.map((o) => `${o.itemId} @ ${o.perBaseUnit}`))
        .join("; "),
    ]),
  ]),
);

const money = (value: number | null) =>
  value === null ? "-" : `$${value.toFixed(value < 1 ? 4 : 2)}`;

function savings(row: MappingRow): string {
  const prices = Object.values(row.suppliers)
    .map(({ best }) => best.perBaseUnit)
    .filter((p): p is number => p !== null)
    .sort((a, b) => a - b);
  if (prices.length < 2) return "-";
  return `${Math.round((1 - prices[0] / prices[prices.length - 1]) * 100)}%`;
}

const reviewKinds: Record<string, string> = {
  match: "Matches to confirm",
  handwritten: "Handwritten changes",
  "missing-price": "Missing prices",
  "unclear-unit": "Unclear units",
  "pack-size": "Pack and carton sizes",
  data: "Other data questions",
};

const summary = [
  "# Material catalog summary",
  "",
  "Generated by `npm.cmd run catalog`. Do not edit by hand.",
  "",
  "## Suppliers",
  "",
  "| Supplier | Source | Pages | Prices as of | Items | Gutter items |",
  "|---|---|---|---|---|---|",
  ...suppliers.map((s) => {
    const items = catalog.filter((i) => i.supplier === s.id);
    return `| ${s.name} | \`${s.sourceFile.split("/").pop()}\` | ${s.pages} | ${s.asOf} (scan date) | ${items.length} | ${items.filter((i) => i.gutterRelevant).length} |`;
  }),
  "",
  "## Items by category",
  "",
  `| Category | ${suppliers.map((s) => s.name).join(" | ")} | Total |`,
  `|---|${suppliers.map(() => "---|").join("")}---|`,
  ...categories.map((category) => {
    const counts = suppliers.map(
      (s) => catalog.filter((i) => i.supplier === s.id && i.category === category).length,
    );
    return `| ${category} | ${counts.join(" | ")} | ${counts.reduce((a, b) => a + b, 0)} |`;
  }),
  "",
  "## Products carried by both suppliers",
  "",
  `| Canonical item | Base unit | ${suppliers.map((s) => s.name).join(" | ")} | Cheaper | Difference |`,
  `|---|---|${suppliers.map(() => "---|").join("")}---|---|`,
  ...mappingTable
    .filter((row) => row.status === "matched")
    .map((row) => {
      const cells = supplierIds.map((s) => {
        const best = row.suppliers[s]?.best;
        if (!best) return "not carried";
        const flag = best.confidence === "high" ? "" : ` (${best.confidence})`;
        return `${money(best.perBaseUnit)}${flag}`;
      });
      const cheaper = suppliers.find((s) => s.id === row.cheapestSupplier)?.name ?? "-";
      return `| ${row.name} | ${row.baseUnit} | ${cells.join(" | ")} | ${cheaper} | ${savings(row)} |`;
    }),
  "",
  `${mappingTable.filter((r) => r.status === "single-supplier").length} more canonical items are carried by one supplier only. See \`canonical-map.csv\`.`,
  "",
].join("\n");

const reviewDoc = [
  "# Needs review",
  "",
  "Generated by `npm.cmd run catalog`. Fix answers in the transcription or canonical data files, then rebuild.",
  "",
  ...Object.entries(reviewKinds).flatMap(([kind, title]) => {
    const entries = review.filter((e) => e.kind === kind);
    if (entries.length === 0) return [];
    return [
      `## ${title} (${entries.length})`,
      "",
      ...entries.map((e) => {
        const ids = e.itemIds.length > 0 && e.itemIds.length <= 3 ? ` \`${e.itemIds.join("`, `")}\`` : "";
        return `- ${e.message}${ids}`;
      }),
      "",
    ];
  }),
].join("\n");

write("summary.md", summary);
write("needs-review.md", reviewDoc);

console.log(
  JSON.stringify(
    {
      items: catalog.length,
      bySupplier: Object.fromEntries(
        suppliers.map((s) => [s.id, catalog.filter((i) => i.supplier === s.id).length]),
      ),
      gutterItems: catalog.filter((i) => i.gutterRelevant).length,
      canonicalItems: mappingTable.length,
      matched: mappingTable.filter((r) => r.status === "matched").length,
      singleSupplier: mappingTable.filter((r) => r.status === "single-supplier").length,
      reviewEntries: Object.fromEntries(
        Object.keys(reviewKinds).map((k) => [k, review.filter((e) => e.kind === k).length]),
      ),
    },
    null,
    2,
  ),
);
